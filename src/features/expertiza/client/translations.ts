export function translate(locale: Locale, text: string): string {
  return locale === "ru" ? russian[text] ?? text : text;
}

export function countText(locale: Locale, count: number, ro: string, ru: [string, string, string]): string {
  const rule = new Intl.PluralRules("ru").select(count);
  return `${count} ${locale === "ro" ? ro : ru[rule === "one" ? 0 : rule === "few" ? 1 : 2]}`;
}
